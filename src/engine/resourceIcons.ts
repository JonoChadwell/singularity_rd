const BY_NAME = new Map(Object.entries(RESOURCE_ICONS).map(([name, icon]) => [name.toLowerCase(), icon]))

/** The ready-made icon for a resource name (ignoring case and edge spaces), if it has one. */
export function knownResourceIcon(name: string): string | null {
  return BY_NAME.get(name.trim().toLowerCase()) ?? null
}
